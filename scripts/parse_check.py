"""Every printed program read by the parser of the CakeML source itself, inside HOL4.

`write TREES DIR` turns each program of `dn-compiler emit-trees` into a theory of its own, whose
script reads the program's text from a file of its octets, evaluates `parse_topdecs_to_ast`, the
parser `compile_pancake` reads its input with (`compiler/compilerScript.sml`), on it, saves the
equation as a theorem and writes the tree it gives as JSON (backend/parser/dnParseShowLib.sml).
`compare TREES DIR` brings each tree to the canonical form of scripts/parser_contract.py and
requires it to be the program's lowering, function by function, each exported exactly when its
text says so, and no function besides. With `--cells CELLS`, the precedence table of
`dn-compiler emit-cells`, one more theory reads each cell's text, and each cell has to be read as
the table says (`cells_read`). `--lean PROGRAMS READINGS`, what `dn-compiler parse-trees` and
`parse-cells` give, holds DN.Compiler.Parse, the Lean copy of the parser, to the same trees exactly,
the annotation of a statement's place aside, or to the same refusal. `--defect` regroups a
subtraction in the one program that holds it, which the comparison then has to see as a tree
other than the lowering (`--expect-differences`). The JSON printer and this comparison are not
proved; the theorems are.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
from lanes import LaneError  # the path above is what makes these importable
import parser_contract as contract

PANLANG = "panLang$"
# The theories whose constants a tree names without arguments: panLang's, the machine's operators and
# CakeML's shifts.
NULLARY = ("panLang", "asm", "ast")
# Statements nest as deep as a program's blocks are long.
sys.setrecursionlimit(100_000)


def theory(k: int) -> str:
    return f"dnParse{k}"


def script(k: int, name: str) -> str:
    """The theory of program `k`: its text read from its file, an octet a character as the
    compiler reads it, the parser's equation at 64-bit words, and the tree."""
    return f"""(* SPDX-License-Identifier: AGPL-3.0-or-later *)
(* Generated by scripts/parse_check.py: the printed program {k}, {name}. *)
open HolKernel boolLib bossLib panPtreeConversionTheory;
val _ = new_theory "{theory(k)}";
val source = let val i = BinIO.openIn "{theory(k)}.pnk" in BinIO.inputAll i before BinIO.closeIn i end;
val text = stringSyntax.fromMLstring (Byte.bytesToString source);
val parse = inst [alpha |-> fcpSyntax.mk_int_numeric_type 64] ``parse_topdecs_to_ast``;
val dn_parse_{k} = save_thm ("dn_parse_{k}", EVAL (mk_comb (parse, text)));
val _ = dnParseShowLib.show "{theory(k)}.json" (mk_comb (parse, text)) dn_parse_{k};
val _ = export_theory ();
"""


CELLS = "dnParseCells"


def cells_script(count: int) -> str:
    """The theory of the table's cells: the parser's equation on each cell's text, saved, and the
    trees as one JSON list, `null` for a text the parser refuses."""
    return f"""(* SPDX-License-Identifier: AGPL-3.0-or-later *)
(* Generated by scripts/parse_check.py: the {count} cells of the precedence table. *)
open HolKernel boolLib bossLib panPtreeConversionTheory;
val _ = new_theory "{CELLS}";
fun source k =
  let val i = BinIO.openIn ("dnCell" ^ Int.toString k ^ ".pnk") in BinIO.inputAll i before BinIO.closeIn i end;
val parse = inst [alpha |-> fcpSyntax.mk_int_numeric_type 64] ``parse_topdecs_to_ast``;
fun text k = stringSyntax.fromMLstring (Byte.bytesToString (source k));
val parses = List.tabulate ({count}, fn k => mk_comb (parse, text k));
val ths = List.tabulate ({count}, fn k => save_thm ("dn_cell_" ^ Int.toString k, EVAL (List.nth (parses, k))));
val _ = dnParseShowLib.showEach "{CELLS}.json" (ListPair.zip (parses, ths));
val _ = export_theory ();
"""


def chain(op: str, e: list[Any]) -> list[list[Any]]:
    return chain(op, e[1]) + chain(op, e[2]) if e[0] == op else [e]


def head(form: Any) -> str:
    if not (isinstance(form, list) and form and isinstance(form[0], str) and form[0].startswith(PANLANG)):
        raise LaneError(f"not a constructor of panLang: {str(form)[:120]}")
    return form[0].removeprefix(PANLANG)


def nullary(form: Any) -> str:
    """The name of a constructor without arguments, of one of the theories `NULLARY` names."""
    if not (isinstance(form, list) and len(form) == 1 and isinstance(form[0], str)
            and form[0].partition("$")[0] in NULLARY and form[0].partition("$")[2]):
        raise LaneError(f"not a constant: {str(form)[:120]}")
    return form[0].partition("$")[2]


def expression(form: Any) -> list[Any]:
    h, args = head(form), form[1:]
    if h == "Const" and len(args) == 1 and isinstance(args[0], int):
        return ["Const", args[0]]
    if h == "Var" and len(args) == 2 and nullary(args[0]) == "Local" and isinstance(args[1], str):
        return ["Var", args[1]]
    if h == "BaseAddr" and not args:
        return ["BaseAddr"]
    if h == "Op" and len(args) == 2:
        op, operands = nullary(args[0]), args[1]
        if op in ("Add", "And", "Xor", "Or") and len(operands) >= 2:
            flat = [x for o in operands for x in chain(op, expression(o))]
            return contract.right_nested(op, flat)
        if op == "Sub" and len(operands) == 2:
            return ["Sub", expression(operands[0]), expression(operands[1])]
    if h == "Panop" and len(args) == 2 and nullary(args[0]) == "Mul" and len(args[1]) == 2:
        flat = [x for o in args[1] for x in chain("Mul", expression(o))]
        return contract.right_nested("Mul", flat)
    if h == "Cmp" and len(args) == 3 and nullary(args[0]) in ("Less", "NotLess", "Equal"):
        return [nullary(args[0]), expression(args[1]), expression(args[2])]
    if h == "Shift" and len(args) == 3 and nullary(args[0]) in ("Lsr", "Lsl") and isinstance(args[2], int):
        return [nullary(args[0]), expression(args[1]), ["Const", args[2]]]
    if h == "Load" and len(args) == 2 and head(args[0]) == "One":
        return ["MemLoad", expression(args[1])]
    if h == "LoadByte" and len(args) == 1:
        return ["MemLoadByte", expression(args[0])]
    raise LaneError(f"an expression form this check does not know: {str(form)[:160]}")


def one(shape: Any) -> bool:
    return isinstance(shape, list) and len(shape) == 1 and shape[0] == PANLANG + "One"


def block(form: Any) -> list[Any]:
    h, args = head(form), form[1:]
    if h in ("Skip", "Annot"):
        return []
    if h == "Seq" and len(args) == 2:
        return block(args[0]) + block(args[1])
    if h == "Dec" and len(args) == 4 and one(args[1]):
        return [["dec", args[0], expression(args[2]), block(args[3])]]
    if h == "Assign" and len(args) == 3 and nullary(args[0]) == "Local":
        return [["assign", args[1], expression(args[2])]]
    if h in ("Store", "StoreByte") and len(args) == 2:
        return [[h.lower(), expression(args[0]), expression(args[1])]]
    if h == "If" and len(args) == 3:
        return [["if", expression(args[0]), block(args[1]), block(args[2])]]
    if h == "While" and len(args) == 2:
        return [["while", expression(args[0]), block(args[1])]]
    if h == "Return" and len(args) == 1:
        return [["return", expression(args[0])]]
    if h == "ExtCall" and len(args) == 5 and isinstance(args[0], str):
        return [["extcall", args[0], *(expression(a) for a in args[1:])]]
    if h == "DecCall" and len(args) == 5 and one(args[1]) and isinstance(args[2], str):
        return [["deccall", args[0], args[2], [expression(a) for a in args[3]], block(args[4])]]
    raise LaneError(f"a statement form this check does not know: {h}")


FIELDS = {"name", "inline", "export", "params", "body", "return"}


def function(decl: Any) -> tuple[str, bool, dict[str, Any]]:
    """A declaration of the parser's tree: a function whose record holds its name, whether it is
    inlined and exported, its parameters, its body and the shape it returns."""
    if head(decl) != "Function" or len(decl) != 2 or not isinstance(decl[1], dict) or set(decl[1]) != FIELDS:
        raise LaneError(f"not a function: {str(decl)[:120]}")
    record = decl[1]
    name, inline, export, params = record["name"], record["inline"], record["export"], record["params"]
    body, returns = record["body"], record["return"]
    if inline is not False or not isinstance(export, bool) or not one(returns) or not isinstance(name, str):
        raise LaneError(f"{name}: a function inlined or returning other than one word")
    names = []
    for param in params:
        if not (isinstance(param, list) and len(param) == 3 and param[0] == "pair$," and isinstance(param[1], str)
                and one(param[2])):
            raise LaneError(f"{name}: a parameter of another shape: {param}")
        names.append(param[1])
    return name, export, {"params": names, "body": block(body)}


def compared(program: dict[str, Any], tree: list[Any]) -> int:
    """How many functions of `program` the parser's tree holds as they were lowered; a difference
    raises."""
    found = {}
    for decl in tree:
        name, export, f = function(decl)
        if name in found:
            raise LaneError(f"{name}: defined twice in the parser's tree")
        if export != bool(re.search(rf"(?m)^export fun {re.escape(name)}\(", program["source"])):
            raise LaneError(f"{name}: exported {export}, which its text does not say")
        found[name] = f
    want = {f["name"]: {"params": f["params"], "body": f["body"]} for f in (program, *program.get("functions", []))}
    if set(found) != set(want):
        raise LaneError(f"{program['name']}: the parser's tree has the functions {sorted(found)}, not {sorted(want)}")
    for name, f in want.items():
        if found[name] != f:
            raise LaneError(f"{name}: the parser's tree is not the lowered one")
    return len(want)


def unique(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    """A JSON object whose keys are all different, as a record's fields are."""
    if len({k for k, _ in pairs}) != len(pairs):
        raise LaneError(f"an object with a key twice: {[k for k, _ in pairs]}")
    return dict(pairs)


def tree(path: Path) -> Any:
    return json.loads(path.read_text(), object_pairs_hook=unique)


def cells_read(cells: list[dict[str, Any]], readings: list[Any]) -> int:
    """Each cell read as the table says: one it lets an operand stand in bare as intended, any
    other refused (`None`) or read otherwise."""
    if len(readings) != len(cells):
        raise LaneError(f"{len(readings)} readings of {len(cells)} cells")
    for cell, reading in zip(cells, readings, strict=True):
        if cell["reads"]:
            if reading is None:
                raise LaneError(f"{cell['cell']}: refused, which the table says is read")
            compared(cell["tree"], reading)
        elif reading is not None:
            try:
                compared(cell["tree"], reading)
            except LaneError as error:
                if contract.MISREAD in str(error):
                    continue
                raise
            raise LaneError(f"{cell['cell']}: read as one operand, which the table says it is not")
    return len(cells)


def write(trees: Path, out: Path, defect: bool, cells: Path | None = None) -> None:
    programs = json.loads(trees.read_text())
    out.mkdir(parents=True, exist_ok=True)
    chosen = list(enumerate(programs))
    if defect:
        old, new = contract.REGROUPED
        holding = [(k, p) for k, p in chosen if p["source"].count(old) == 1]
        if not holding:
            raise LaneError(f"no printed program holds {old!r} once, for the defect")
        k, p = holding[0]
        chosen = [(k, {**p, "source": p["source"].replace(old, new)})]
    for k, p in chosen:
        (out / f"{theory(k)}.pnk").write_bytes(p["source"].encode())
        (out / f"{theory(k)}Script.sml").write_text(script(k, p["name"]))
    targets = [f"{theory(k)}Theory.uo" for k, _ in chosen]
    if cells:
        table = json.loads(cells.read_text())
        for k, cell in enumerate(table):
            (out / f"dnCell{k}.pnk").write_bytes(cell["tree"]["source"].encode())
        (out / f"{CELLS}Script.sml").write_text(cells_script(len(table)))
        targets.append(f"{CELLS}Theory.uo")
    (out / "targets").write_text("".join(f"{t}\n" for t in targets))


LOCATION = [PANLANG + "Annot", "location"]


def unplaced(form: Any) -> Any:
    """The tree with the annotation `conv_Prog` puts before each statement, its place, left out."""
    if isinstance(form, list):
        if len(form) == 3 and form[0] == PANLANG + "Seq" and isinstance(form[1], list) and form[1][:2] == LOCATION:
            return unplaced(form[2])
        return [unplaced(x) for x in form]
    if isinstance(form, dict):
        return {k: unplaced(v) for k, v in form.items()}
    return form


def compare(trees: Path, out: Path, expect_differences: bool, cells: Path | None = None,
            lean: tuple[Path, Path] | None = None) -> None:
    if lean and not cells:
        raise LaneError("the Lean parser's readings of the cells need the cells")
    programs = json.loads(trees.read_text())
    copies, readings = (json.loads(path.read_text()) for path in lean) if lean else (None, None)
    if copies is not None and len(copies) != len(programs):
        raise LaneError(f"the Lean parser read {len(copies)} programs of {len(programs)}")
    targets = [t for t in (out / "targets").read_text().split() if t != f"{CELLS}Theory.uo"]
    differences, functions = [], 0
    for target in targets:
        k = int(target.removeprefix("dnParse").removesuffix("Theory.uo"))
        path = out / f"{theory(k)}.json"
        if not path.is_file():
            raise LaneError(f"{theory(k)} wrote no tree")
        try:
            read = tree(path)
            functions += compared(programs[k], read)
        except LaneError as error:
            differences.append(f"{theory(k)}: {error}")
            continue
        if copies is not None and unplaced(read) != copies[k]:
            differences.append(f"{theory(k)}: {programs[k]['name']}: the Lean parser reads it otherwise")
    if expect_differences:
        if not differences or contract.MISREAD not in differences[0]:
            raise LaneError(f"the planted defect was not seen as a tree other than the lowering: {differences}")
        print(f"DN PARSE: the planted defect seen: {differences[0][:200]}")
        return
    if differences:
        raise LaneError("; ".join(differences)[:2000])
    if len(targets) != len(programs):
        raise LaneError(f"{len(targets)} theories for {len(programs)} printed programs")
    copy = ", and as the Lean parser reads it" if copies is not None else ""
    print(f"DN PARSE: {len(programs)} printed programs, {functions} functions, each read by CakeML's own parser "
          f"in HOL4 as it was lowered{copy}")
    if cells:
        table = json.loads(cells.read_text())
        held = tree(out / f"{CELLS}.json")
        count = cells_read(table, held)
        if readings is not None:
            if len(readings) != len(held):
                raise LaneError(f"the Lean parser read {len(readings)} cells of {len(held)}")
            for cell, hol, copied in zip(table, held, readings, strict=True):
                if (None if hol is None else unplaced(hol)) != copied:
                    raise LaneError(f"{cell['cell']}: the Lean parser reads it otherwise")
        print(f"DN PARSE: {count} cells of the precedence table, each read by CakeML's own parser in HOL4 as the "
              f"table says{copy}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    w = sub.add_parser("write")
    w.add_argument("trees", type=Path)
    w.add_argument("out", type=Path)
    w.add_argument("--defect", action="store_true")
    w.add_argument("--cells", type=Path)
    c = sub.add_parser("compare")
    c.add_argument("trees", type=Path)
    c.add_argument("out", type=Path)
    c.add_argument("--expect-differences", action="store_true")
    c.add_argument("--cells", type=Path)
    c.add_argument("--lean", type=Path, nargs=2)
    args = parser.parse_args()
    try:
        if args.command == "write":
            write(args.trees, args.out, args.defect, args.cells)
        else:
            compare(args.trees, args.out, args.expect_differences, args.cells, args.lean)
    except LaneError as error:
        sys.exit(f"DN PARSE: {error}")


if __name__ == "__main__":
    main()
